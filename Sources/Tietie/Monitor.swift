import AppKit
import Vision

/// 盯著剪貼簿。有新東西就存起來。
final class ClipboardMonitor {
    private let pb = Clip.board
    private let store: Store
    private var lastCount: Int
    private var timer: Timer?
    /// 貼貼自己寫進剪貼簿的那一次不要再記一遍。
    var ignoreCount = -1
    var onChange: (() -> Void)?

    static let maxTextBytes = 5 * 1024 * 1024

    init(store: Store) {
        self.store = store
        self.lastCount = pb.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.tick() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func tick() {
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        if count == ignoreCount { return }
        if Settings.shared.data.paused { return }

        let types = Set((pb.types ?? []).map { $0.rawValue })
        // 其他工具標記為「暫時」或「自動產生」的內容不記
        if types.contains("org.nspasteboard.TransientType") || types.contains("org.nspasteboard.AutoGeneratedType") { return }
        // 密碼管理器標記為機密的內容，看使用者的選擇
        // 使用者還沒做完第一次設定之前，一律先不記
        if types.contains("org.nspasteboard.ConcealedType") && !(Settings.shared.data.recordConcealed && Settings.shared.data.onboarded) { return }

        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""

        // 1. 檔案
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path }.joined(separator: "\n")
            store.addText(paths, kind: "file", sourceApp: app)
            onChange?()
            return
        }

        let string = pb.string(forType: .string) ?? ""
        let hasImage = types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
            || types.contains("public.jpeg")

        // 2. 圖片（沒有文字，或文字只是這張圖的網址）
        if hasImage && (string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty || ClipboardMonitor.looksLikeSingleURL(string)) {
            if let (png, w, h) = ClipboardMonitor.readImage(pb) {
                if let id = store.addImage(png: png, width: w, height: h, sourceApp: app) {
                    recognizeText(id: id, png: png)
                }
                onChange?()
                return
            }
        }

        // 3. 文字（只存純文字，所以貼出來一定是乾淨的）
        if !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, string.utf8.count <= ClipboardMonitor.maxTextBytes {
            store.addText(string, sourceApp: app)
            onChange?()
        }
    }

    static func looksLikeSingleURL(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(" "), !t.contains("\n") else { return false }
        return t.hasPrefix("http://") || t.hasPrefix("https://") || t.hasPrefix("file://") || t.hasPrefix("data:")
    }

    static func readImage(_ pb: NSPasteboard) -> (Data, Int, Int)? {
        if let png = pb.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        if let jpeg = pb.data(forType: NSPasteboard.PasteboardType("public.jpeg")), let rep = NSBitmapImageRep(data: jpeg),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        return nil
    }

    /// 在背景把圖片裡的字讀出來，之後打字就搜得到這張圖。全程在本機完成。
    func recognizeText(id: Int64, png: Data) {
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let text = ClipboardMonitor.ocr(png: png)
            guard !text.isEmpty else { return }
            DispatchQueue.main.async {
                self?.store.setOCR(id: id, text: text)
            }
        }
    }

    static func ocr(png: Data) -> String {
        guard let source = CGImageSourceCreateWithData(png as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return "" }
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.recognitionLanguages = ["zh-Hant", "en-US"]
        request.usesLanguageCorrection = true
        let handler = VNImageRequestHandler(cgImage: image, options: [:])
        do {
            try handler.perform([request])
        } catch {
            return ""
        }
        let lines = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }
        return lines.joined(separator: "\n")
    }
}
